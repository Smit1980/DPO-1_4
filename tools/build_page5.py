def expand_prompts5(body: str) -> str:
    for pid, p in PROMPT5_BY_ID.items():
        body = body.replace(f"{{{{PROMPT5:{pid}}}}}", prompt_box(p))
        body = body.replace(f"{{{{PK5:{pid}}}}}", prompt_box(p, "pk5"))
    left = re.findall(r"\{\{[^}]+\}\}", body)
    if left:
        raise SystemExit("нераскрытые плейсхолдеры: " + ", ".join(left))
    return body


