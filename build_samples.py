"""Create clearly synthetic documents for the lecture, never real corporate data."""
from pathlib import Path
import csv
from openpyxl import Workbook,load_workbook
from openpyxl.comments import Comment
from docx import Document
R=Path(__file__).resolve().parent/"downloads"
rows=[
["З-01","Сотрудник А","принтер","02.09 09:15","407",15],
["З-02","Сотрудник Б","принтер","02.09 11:20","408",25],
["З-03","Сотрудник В","сканер","03.09 08:30","409",10],
["З-04","Сотрудник Г","принтер","03.09 17:45","410",20],
["З-05","Сотрудник Д","подключение","04.09 12:00","411",30],
]
with (R/"synthetic-data.csv").open("w",encoding="utf-8-sig",newline="") as f:
    w=csv.writer(f,delimiter=";")
    w.writerow(["Учебная заявка","Условный сотрудник","Категория","Условное время","Условный кабинет","Минуты"])
    w.writerows(rows)
with (R/"synthetic-minimal.csv").open("w",encoding="utf-8-sig",newline="") as f:
    w=csv.writer(f,delimiter=";"); w.writerow(["Категория"]);w.writerows([[r[2]] for r in rows])
b=Workbook();s=b.active;s.title="Учебные заявки"
s.append(["СИНТЕТИЧЕСКИЕ ДАННЫЕ. Полностью вымышленные строки."])
s.append(["Заявка","Условный сотрудник","Категория","Условное время","Условный кабинет","Минуты"])
for row in rows:s.append(row)
s["B3"].comment=Comment("УЧЕБНАЯ ЛОВУШКА: комментарий остался в файле. Не содержит реальных сведений.","Учебный автор")
h=b.create_sheet("Скрытый учебный лист");h.append(["УЧЕБНАЯ ЛОВУШКА","Ненужные сведения на скрытом листе"]);h.sheet_state="hidden"
b.properties.creator="УЧЕБНЫЙ АВТОР — СИНТЕТИЧЕСКИЙ ПРИМЕР"
b.save(R/"synthetic-file-layers.xlsx")
assert load_workbook(R/"synthetic-file-layers.xlsx")["Скрытый учебный лист"].sheet_state=="hidden"
doc=Document();doc.add_heading("Учебная записка: перенос профилактики",0)
doc.add_paragraph("СИНТЕТИЧЕСКИЙ ПРИМЕР. Ни один реквизит не относится к реальному человеку или организации.")
doc.add_paragraph("Задача — получить пустой шаблон письма, без фактических реквизитов.")
doc.add_paragraph("Черновик: Сотрудник 1; единственный специалист смены; 23:15; телефон 000-00-00; кабинет 407. Согласование требуется уточнить.")
doc.add_paragraph("Минимальная версия: Переносим профилактику [ОБОРУДОВАНИЕ] на [ДАТА]. Организационные вопросы: [КОНТАКТ].")
doc.sections[0].header.paragraphs[0].text="УЧЕБНЫЙ КОЛОНТИТУЛ — тоже часть документа"
doc.core_properties.author="УЧЕБНЫЙ АВТОР"
doc.core_properties.comments="УЧЕБНЫЕ МЕТАДАННЫЕ: проверьте свойства файла"
doc.save(R/"synthetic-note.docx")
(R/"synthetic-files-readme.md").write_text("""# Учебные файлы для показа
Все значения вымышлены. Они не описывают сотрудников, оборудование или сеть организации.

- synthetic-file-layers.xlsx: пять заявок; примечание B3; скрытый лист; учебное поле «Автор».
- synthetic-note.docx: перегруженный черновик, минимальный шаблон, колонтитул и учебные свойства документа.
- synthetic-data.csv: исходные пять учебных строк.
- synthetic-minimal.csv: только категории, достаточные для подсчёта.

## Покажите на экране за 4 минуты
1. Откройте XLSX локально, прочитайте пять строк. Вопрос: «Всё ли содержимое видно сейчас?»
2. Откройте примечание B3 и отобразите скрытый лист обычными средствами редактора. Покажите свойства. Это заранее созданные учебные ловушки, не настоящая утечка.
3. Откройте minimal.csv. Сверьте 3 принтера, 1 сканер, 1 подключение — 5 записей.
4. Объясните: новый минимальный файл проще проверить, но он не отменяет правила разрешённого контура. Наличие CSV не является сертификатом обезличивания.
5. При отсутствии офисного редактора используйте текстовые данные на странице. Не отправляйте рабочие файлы в онлайн-конвертер.

Эти четыре минуты включены в повторение первой пары; не прибавляйте их поверх тайминга.
""",encoding="utf-8")
print("Synthetic XLSX, DOCX and two CSV created and verified")
